#!/usr/bin/env bash
# PreToolUse[Write|Edit|NotebookEdit] — TRACE-BOUNDED AUTONOMY (R86). While autopilot is armed, an
# agent may freely do work that SATISFIES the recorded contract, but it may not silently CHANGE it.
#
# Three tiers, and the reason this is enforceable at all is that the contract is now FILES:
#   satisfies an existing requirement   → ordinary work. This guard says nothing.
#   would CHANGE or ADD a requirement   → refused; park the proposed delta as a ❓ for the owner.
#   would author a NEED                 → refused outright. Needs define what "useful" MEANS, so an
#                                         agent that writes its own has no falsifiable standard left.
#
# WHY THIS SHAPE AND NOT A V-LEVEL DIAL (owner-asked 2026-08-02, considered and rejected): "is this
# an L2 task?" is a judgement the agent would make — the very judgement the bound exists to
# constrain, and unauditable after the fact. "Does this edit the contract?" is a path comparison.
# It also adds no fifth mode: four already exist (autopilot/decisive/sweep/burndown) and most of
# this project's mode defects came from their interaction, so this is a rule, not a dimension.
#
# NOT a security control. An agent that wants to edit these files can do it another way; this stops
# the ACCIDENTAL and the well-meant — an unattended run quietly rewriting what it is measured
# against, which is the failure the whole trace matrix exists to make impossible.
# Silent when autopilot is off: the owner is present and can simply decide.
# Best-effort (R7/R68): any failure allows the write rather than blocking the session.
set -uo pipefail
command -v jq >/dev/null 2>&1 || exit 0
SELF="${BASH_SOURCE[0]}"
while [ -L "$SELF" ]; do
  link="$(readlink "$SELF")"
  case "$link" in /*) SELF="$link" ;; *) SELF="$(dirname "$SELF")/$link" ;; esac
done
# shellcheck source=../lib/companion.sh
. "$(cd "$(dirname "$SELF")/../lib" && pwd)/companion.sh"

in="$(cat 2>/dev/null || true)"
cwd="$(printf '%s' "$in" | jq -r '.cwd // empty' 2>/dev/null || true)"; [ -n "$cwd" ] || cwd="$PWD"
root="$(companion_root "$cwd")"
companion_autopilot_on "$root" || exit 0

path="$(printf '%s' "$in" | jq -r '.tool_input.file_path // .tool_input.notebook_path // empty' 2>/dev/null || true)"
[ -n "$path" ] || exit 0

# Compare on the trailing path only, so it works whether the tool reports an absolute or a
# repo-relative path, and in any repo laying the contract out this way (the plugin's own
# convention — not an ecosystem allowlist, R9).
case "$path" in
  */docs/needs.yaml|docs/needs.yaml)
    reason="REFUSED — docs/needs.yaml is the NEEDS layer, and needs are never yours to write. A need is the definition of what \"useful\" means here; an agent that authors its own has nothing left to be measured against, and every requirement below it inherits that. This holds regardless of how good the change looks. If you believe a need is missing, wrong, or newly implied by the work: PARK it as a proposal — \`tq add \"❓ [parked] needs.yaml: <the need you'd add, in outcome language> — why it is implied by <what you were doing>; rec: <add it / do not>\"\` — and carry on with the rest of the work. Do not edit this file while autopilot is armed." ;;
  */docs/requirements.yaml|docs/requirements.yaml)
    reason="REFUSED — docs/requirements.yaml is the CONTRACT, and changing it while unattended is how an agent quietly rewrites what it is measured against. Adding, removing, or reinterpreting a requirement is a decision the owner makes. PARK the delta instead, with enough detail that the review is a real choice: \`tq add \"❓ [parked] requirements.yaml: <add|change|remove> R__ — <the exact proposed text>; because: <what in the work implies it>; rec: <your pick> + why\"\` — then continue with the work that does NOT depend on the answer. Satisfying an EXISTING requirement needs no permission and is not affected by this." ;;
  *) exit 0 ;;
esac

jq -cn --arg r "$reason" '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: "deny", permissionDecisionReason: $r}}'
